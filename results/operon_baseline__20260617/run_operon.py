"""run_operon.py — Operon LMOptimizer CO side of the baseline, ONE problem cell.

Run under the operon venv:
    /home/weish/hao/operon-venv/bin/python results/operon_baseline__20260617/run_operon.py \\
        --dataset feynman/I.18.12 --max-iter 200 --out results/operon_baseline__20260617/data

For (dataset, cap32, seed0, noise0): regenerate the EXACT committed corpus trees via
``operon_dump.run_cell(_return_internals=True)`` (one GP run to max gen), then for each
checkpoint gen run Operon's own ``CoefficientOptimizer(LMOptimizer)`` on every tree,
starting from the harvested ``c_init`` (proven same start), and score the returned tree
with the neutral fp64 0.5*SSE (``lib.half_sse``). Emits ``<safe>__operon.json``.

Baked-in honesty gates (the advisor's blocking items + the user's anti-cheat ask):
  * Probe B: the regenerated ``pop_gen{g}.bin`` MUST be byte-identical to the committed
    corpus bin (else we are not optimizing the corpus trees) — recorded per gen.
  * alignment: M == len(snaps[g]) and per-tree K matches the committed bin metas
    (so tree m on the Operon side == tree m in the kernel's pop.bin).
  * keeps-best guard: loss_operon <= loss_start (Operon never returns worse-than-start);
    any violation is COUNTED and recorded, never silently clamped.
  * DispatchTable is held in a named var for the whole loop (pyoperon lifetime gotcha).
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np
import pyoperon as op

ROOT = Path("/home/weish/hao/CuSR")
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "results/operon_baseline__20260617"))
from cusr.benchmark.workload.operon_dump import run_cell, _grammar_int
from cusr.benchmark.workload.operon_adapter import build_hash2idx, convert
from cusr.benchmark.workload.pop_io import read_pop_bin
from lib import half_sse, GENS, CAP, SEED, NOISE, POP, N, committed_cell_dir

SNAP = ROOT / "data/workload/snapshots"


def run(dataset, max_iter, out_dir, gens=GENS):
    safe = dataset.replace("/", "_")
    tmp = Path("/tmp/baseline_operon") / safe
    tmp.mkdir(parents=True, exist_ok=True)
    t0 = time.time()

    manifest, _, intern = run_cell(
        dataset=dataset, pop=POP, N=N, seed=SEED, noise=NOISE, cap=CAP,
        checkpoint_gens=gens, out=tmp / "pop.bin", threads=1, _return_internals=True)
    snaps, hash2idx, X, y = intern["snaps"], intern["hash2idx"], intern["X"], intern["y"]
    n_vars = X.shape[1]

    # Operon Problem + DispatchTable (HELD) — mirror run_cell's construction exactly.
    ds = op.Dataset(np.asfortranarray(np.column_stack([X, y]).astype(np.float64)))
    V = ds.Variables
    assert build_hash2idx(ds) == hash2idx, "rebuilt dataset hashes differ"
    pr = op.Problem(ds)
    pr.TrainingRange = op.Range(0, N); pr.TestRange = op.Range(0, N)
    pr.Target = V[n_vars]; pr.InputHashes = [v.Hash for v in V[:n_vars]]
    pr.ConfigurePrimitiveSet(_grammar_int())
    dt = op.DispatchTable()                      # HELD (lifetime gotcha)
    lm = op.LMOptimizer(dt, pr, max_iter=max_iter)
    co = op.CoefficientOptimizer(lm)

    cell_committed = committed_cell_dir(SNAP, dataset)
    result = dict(dataset=dataset, cap=CAP, seed=SEED, noise=NOISE, pop=POP, N=N,
                  max_iter=max_iter, engine="operon", gens={})

    for g in gens:
        trees = snaps[g]
        # Probe B: regenerated bytes == committed bytes
        regen_bin = tmp / f"pop_gen{g:04d}.bin"
        comm_bin = cell_committed / f"pop_gen{g:04d}.bin"
        probe_b = (regen_bin.read_bytes() == comm_bin.read_bytes()) if comm_bin.exists() else None

        pop_regen = read_pop_bin(regen_bin)
        M = pop_regen["M_prob"]
        aligned = (M == len(trees))      # 0 drops => snaps order == bin order

        Ks, loss_start, loss_op, success, iters, fevals = [], [], [], [], [], []
        worse_than_start = 0
        kmismatch = 0
        for m, tree in enumerate(trees):
            nt, nv, ci, c0 = convert(tree, hash2idx)
            K = len(c0)
            if aligned and int(pop_regen["metas"][m, 3]) != K:
                kmismatch += 1
            raw0 = half_sse(nt, nv, ci, c0, X, y)
            otree, _summ = co(op.RandomGenerator(SEED), tree)
            nt1, nv1, ci1, c1 = convert(otree, hash2idx)
            raw1 = half_sse(nt1, nv1, ci1, c1, X, y)
            if raw1 > raw0 * (1 + 1e-6) + 1e-9:
                worse_than_start += 1
            Ks.append(K)
            loss_start.append(raw0)
            loss_op.append(raw1)
            success.append(bool(_summ.Success))
            iters.append(int(_summ.Iterations))
            fevals.append(int(_summ.FunctionEvaluations))

        result["gens"][str(g)] = dict(
            M=M, probe_b_identical=probe_b, aligned=aligned, k_mismatch=kmismatch,
            worse_than_start=worse_than_start,
            K=Ks, loss_start=loss_start, loss_operon=loss_op,
            success=success, iters=iters, func_evals=fevals,
        )
        print(f"[operon {dataset} g{g:>3}] M={M} probeB={probe_b} aligned={aligned} "
              f"kmis={kmismatch} worse={worse_than_start} "
              f"improved={sum(1 for a,b in zip(loss_op,loss_start) if b-a>1e-9)}/{M}",
              flush=True)

    result["wall_s"] = round(time.time() - t0, 1)
    out = Path(out_dir) / f"{safe}__operon.json"
    out.write_text(json.dumps(result))
    print(f"[operon {dataset}] -> {out}  ({result['wall_s']}s)", flush=True)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--max-iter", type=int, default=200)
    ap.add_argument("--out", default=str(ROOT / "results/operon_baseline__20260617/data"))
    ap.add_argument("--gens", default=",".join(map(str, GENS)))
    a = ap.parse_args()
    gens = [int(x) for x in a.gens.split(",") if x.strip()]
    run(a.dataset, a.max_iter, a.out, gens)


if __name__ == "__main__":
    main()
