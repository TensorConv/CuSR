"""probe_lm.py — gate the Operon-LMOptimizer-vs-kernel baseline (advisor's blocking items).

Run with the operon venv:
    /home/weish/hao/operon-venv/bin/python /tmp/probe_lm.py

Proves, EMPIRICALLY, before any harness is built:
  Probe B  — run_cell(_return_internals=True) regenerates the EXACT committed corpus
             trees: convert(regenerated) -> pop.bin is byte-identical to the committed
             pop_gen{g}.bin  (=> "identical pre-CO trees" is real, determinism holds).
  Probe A1 — same START: Operon's LMOptimizer begins from the harvested c_init
             (summary.InitialParameters == tree.GetCoefficients()), no random restart.
  Probe A2 — same OBJECTIVE shape: summary.InitialCost / FinalCost track the RAW
             0.5*sum((f-y)^2) (NOT a linearly-scaled a+b*f objective). If linear
             scaling were on, InitialCost would be ~0 even at a wrong c_init.
  Probe A3 — same K: len(summary.FinalParameters) == K (no extra DOF), and the
             optimized loss improves (raw1 <= raw0).
  Probe A4 — determinism: two runs from the same start with different RNG seeds give
             the same FinalParameters (no stochastic restart advantage).
"""
import sys
from pathlib import Path

import numpy as np
import pyoperon as op

ROOT = Path("/home/weish/hao/CuSR")
sys.path.insert(0, str(ROOT))
from cusr.benchmark.workload.operon_dump import run_cell, _grammar_int
from cusr.benchmark.workload.operon_adapter import build_hash2idx, convert
from cusr.benchmark.workload.pop_io import read_pop_bin

CELL = "feynman/I.18.12"
CAP, SEED, NOISE, POP, N = 32, 0, 0.0, 4000, 1000
GENS = [0, 16]                       # gen0 (initial pop) + an evolved gen
COMMITTED = ROOT / "data/workload/snapshots/operon_feynman_I.18.12_pop4000_noise0_len32_seed0"
TMP = Path("/tmp/probe_regen"); TMP.mkdir(parents=True, exist_ok=True)

_UF = {14: np.sin, 15: np.cos, 16: np.tan}
def eval_fp64(nt, nv, ci, c_init, X):
    """fp64 reverse-stack eval over pop.bin arrays (neutral arbiter; mirrors the kernel)."""
    X = np.asarray(X, dtype=np.float64); st = []
    for i in range(len(nt) - 1, -1, -1):
        t = int(nt[i]); v = nv[i]
        if t == 0:   st.append(X[:, int(v)].astype(np.float64))
        elif t == 1: st.append(np.full(X.shape[0], float(c_init[int(ci[i])]), np.float64))
        elif t == 2: st.append(_UF[int(v)](st.pop()))
        elif t == 3:
            l = st.pop(); rv = st.pop(); f = int(v)
            st.append(l + rv if f == 1 else l - rv if f == 2 else l * rv if f == 3 else l / rv)
        else: raise ValueError(t)
    return st[0]

def half_sse(nt, nv, ci, c_init, X, y):
    pred = eval_fp64(nt, nv, ci, c_init, X)
    return 0.5 * float(np.sum((pred - np.asarray(y, np.float64)) ** 2))

print("=== regenerate cell (single source of truth = operon_dump.run_cell) ===", flush=True)
manifest, _, internals = run_cell(
    dataset=CELL, pop=POP, N=N, seed=SEED, noise=NOISE, cap=CAP,
    checkpoint_gens=GENS, out=TMP / "pop.bin", threads=1, _return_internals=True)
snaps, hash2idx, X, y = internals["snaps"], internals["hash2idx"], internals["X"], internals["y"]
n_vars = X.shape[1]
print(f"regenerated gens {sorted(snaps)}  n_vars={n_vars}  X{X.shape} y{y.shape}", flush=True)

# ---- Probe B: byte-identical to committed corpus -------------------------------
print("\n=== Probe B: regenerated bytes == committed corpus bytes ===", flush=True)
b_ok = True
for g in GENS:
    regen = (TMP / f"pop_gen{g:04d}.bin").read_bytes()
    comm = (COMMITTED / f"pop_gen{g:04d}.bin").read_bytes()
    same = regen == comm
    b_ok &= same
    print(f"  gen{g:>3}: regen {len(regen)} B vs committed {len(comm)} B  ->  "
          f"{'IDENTICAL' if same else 'DIFFERENT!!'}", flush=True)
assert b_ok, "Probe B FAILED: regenerated trees are NOT the committed corpus trees"

# Cross-check: the converted arrays for a few trees match what read_pop_bin loads.
pop0 = read_pop_bin(COMMITTED / "pop_gen0000.bin")

# ---- build Problem + DispatchTable for the LMOptimizer (mirror run_cell) --------
ds = op.Dataset(np.asfortranarray(np.column_stack([X, y]).astype(np.float64)))
V = ds.Variables
assert build_hash2idx(ds) == hash2idx, "rebuilt dataset hashes differ from run_cell's"
inputs = [v.Hash for v in V[:n_vars]]
pr = op.Problem(ds)
pr.TrainingRange = op.Range(0, N); pr.TestRange = op.Range(0, N)
pr.Target = V[n_vars]; pr.InputHashes = inputs
pr.ConfigurePrimitiveSet(_grammar_int())
dt = op.DispatchTable()

# Introspect the call mechanics (do not assume).
lm = op.LMOptimizer(dt, pr, max_iter=50)
co = op.CoefficientOptimizer(lm)
print("\n=== optimizer call introspection ===", flush=True)
print("  co.__call__ doc:", (getattr(type(co).__call__, "__doc__", "") or "").strip()[:300], flush=True)

def optimize(tree, rng_seed):
    """Run Operon CO on a tree. Returns (summary, optimized_tree-or-same)."""
    rng = op.RandomGenerator(rng_seed)
    res = co(rng, tree)
    # res may be summary, or (tree, summary), or (summary, tree) — normalize.
    if isinstance(res, tuple):
        a, b = res
        summ = a if hasattr(a, "FinalCost") else b
        otree = b if summ is a else a
        return summ, otree
    return res, tree   # mutated in place

# ---- pick varied-K gen0 trees --------------------------------------------------
gen0 = snaps[0]
picks = []
for t in gen0:
    try:
        nt, nv, ci, c0 = convert(t, hash2idx)
    except Exception:
        continue
    K = len(c0)
    if 1 <= K <= 6 and not any(p[0] == K for p in picks):
        picks.append((K, t, (nt, nv, ci, c0)))
    if len(picks) >= 6:
        break
picks.sort()
print(f"\n=== Probe A: {len(picks)} trees, K = {[p[0] for p in picks]} ===", flush=True)

a_ok = True
for K, tree, (nt, nv, ci, c0) in picks:
    c0_list = [float(x) for x in tree.GetCoefficients()]
    raw0 = half_sse(nt, nv, ci, c0, X, y)
    summ, otree = optimize(tree, rng_seed=0)
    # re-convert the OPTIMIZED tree -> coefficients in correct prefix-slot order
    nt1, nv1, ci1, c1 = convert(otree, hash2idx)
    raw1 = half_sse(nt1, nv1, ci1, c1, X, y)

    IP = [float(x) for x in summ.InitialParameters]
    FP = [float(x) for x in summ.FinalParameters]
    # A1 same start: InitialParameters == harvested coeffs (as a multiset, fp tol)
    same_start = (len(IP) == len(c0_list)
                  and np.allclose(sorted(IP), sorted(c0_list), rtol=1e-5, atol=1e-7))
    # A2 objective shape: InitialCost vs raw0 (ratio reveals 0.5*SSE vs SSE vs scaled~0)
    r_init = (summ.InitialCost / raw0) if raw0 else float("nan")
    r_fin = (summ.FinalCost / raw1) if raw1 else float("nan")
    # A3 same K
    sameK = (len(FP) == K)
    improved = raw1 <= raw0 + 1e-6
    # A4 determinism vs different rng
    summ2, otree2 = optimize(tree, rng_seed=987654321)
    _, _, _, c2 = convert(otree2, hash2idx)
    det = np.allclose(sorted(c1), sorted(c2), rtol=1e-4, atol=1e-6)

    ok = same_start and sameK and improved
    a_ok &= ok
    print(f"  K={K}: start={'OK' if same_start else 'BAD'} "
          f"InitCost/raw0={r_init:.4f} FinCost/raw1={r_fin:.4f} "
          f"sameK={sameK} raw0={raw0:.4g}->raw1={raw1:.4g} "
          f"iters={summ.Iterations} success={summ.Success} det={det}", flush=True)
    if not same_start:
        print(f"      IP={IP[:6]}  c0={c0_list[:6]}", flush=True)

print(f"\nProbe B: {'PASS' if b_ok else 'FAIL'}   Probe A: {'PASS' if a_ok else 'FAIL'}", flush=True)
print("\nNOTE the InitCost/raw0 ratio above: ~1.0 => objective is 0.5*SSE (matches kernel);"
      "\n     ~2.0 => SSE; ~0 => linear scaling masks the start (would BREAK fairness).", flush=True)
